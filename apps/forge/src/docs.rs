//! The generated reference (docs/specs/CLI.md §docs).
//!
//! Every page is rendered from code: the command registry, the clap definition of this
//! tool, the RPC tables of `forge-rpc`, the MCP server's `tools/list` and the script API
//! table of `forge-script`. `forge docs --out docs/manual/reference` writes them; the test
//! `tests/docs.rs` fails when the committed files differ.

use std::collections::BTreeMap;
use std::fmt::Write;

use clap::{Command, CommandFactory};
use forge_app::App;
use forge_command::CommandRegistry;
use serde_json::Value;

use crate::{Cli, EXIT_INTERNAL, EXIT_LOAD, EXIT_USER};

const HEADER: &str = "<!-- Generated by `forge docs`; do not edit. Regenerate: forge docs --out docs/manual/reference -->\n\n";

/// The application the reference describes: no plugins from this machine, plus `plugin.list`.
pub fn docs_app() -> App {
    forge_plugin::load_host(&forge_plugin::HostOptions::none()).new_app()
}

/// `(file name, content)` of every generated page, in a fixed order.
pub fn generate() -> Vec<(&'static str, String)> {
    let app = docs_app();
    vec![
        ("commands.md", commands_markdown(&app.commands)),
        ("cli.md", cli_markdown()),
        ("rpc.md", rpc_markdown()),
        ("mcp.md", mcp_markdown(app)),
        ("scripting.md", scripting_markdown()),
    ]
}

/// The command reference for the default application.
pub fn commands_page() -> String {
    commands_markdown(&docs_app().commands)
}

// ---------------------------------------------------------------- schemas

fn cell(text: &str) -> String {
    text.trim().replace('\n', " ").replace('|', "\\|")
}

fn resolve<'a>(root: &'a Value, schema: &'a Value) -> &'a Value {
    match schema.get("$ref").and_then(Value::as_str) {
        Some(r) => r
            .strip_prefix("#/")
            .and_then(|path| path.split('/').try_fold(root, |v, key| v.get(key)))
            .unwrap_or(schema),
        None => schema,
    }
}

/// A short type name for a (sub)schema.
fn type_name(root: &Value, schema: &Value) -> String {
    let schema = resolve(root, schema);
    if let Some(options) = schema.get("enum").and_then(Value::as_array) {
        return options
            .iter()
            .map(|o| format!("`{o}`"))
            .collect::<Vec<_>>()
            .join(" \\| ");
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(options) = schema.get(key).and_then(Value::as_array) {
            return options
                .iter()
                .map(|o| type_name(root, o))
                .collect::<Vec<_>>()
                .join(" \\| ");
        }
    }
    let kinds: Vec<&str> = match schema.get("type") {
        Some(Value::String(s)) => vec![s.as_str()],
        Some(Value::Array(a)) => a.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    if kinds.is_empty() {
        return "any".into();
    }
    kinds
        .iter()
        .map(|k| match *k {
            "array" => {
                let item = schema
                    .get("items")
                    .map(|i| type_name(root, i))
                    .unwrap_or_else(|| "any".into());
                match (schema.get("minItems"), schema.get("maxItems")) {
                    (Some(a), Some(b)) if a == b => format!("array of {item} (length {a})"),
                    _ => format!("array of {item}"),
                }
            }
            other => other.to_string(),
        })
        .collect::<Vec<_>>()
        .join(" or ")
}

fn description(root: &Value, schema: &Value) -> String {
    let own = schema.get("description").and_then(Value::as_str);
    let referred = resolve(root, schema)
        .get("description")
        .and_then(Value::as_str);
    cell(own.or(referred).unwrap_or(""))
}

/// The arguments of an object schema as a markdown table.
fn schema_table(schema: &Value) -> String {
    let Some(props) = schema.get("properties").and_then(Value::as_object) else {
        return "No arguments.\n".into();
    };
    if props.is_empty() {
        return "No arguments.\n".into();
    }
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut out = String::from("| Argument | Type | Required | Description |\n|---|---|---|---|\n");
    // Required arguments first (in declaration order of `required`), then the rest sorted.
    let mut names: Vec<&String> = props.keys().collect();
    names.sort_by_key(|n| {
        (
            required
                .iter()
                .position(|r| r == &n.as_str())
                .unwrap_or(usize::MAX),
            (*n).clone(),
        )
    });
    for name in names {
        let prop = &props[name];
        let mut text = description(schema, prop);
        if let Some(default) = prop.get("default") {
            let _ = write!(text, " Default: `{default}`.");
        }
        let _ = writeln!(
            out,
            "| `{name}` | {} | {} | {} |",
            type_name(schema, prop),
            if required.contains(&name.as_str()) {
                "yes"
            } else {
                "no"
            },
            text.trim()
        );
    }
    out
}

// ---------------------------------------------------------------- commands

fn commands_markdown(registry: &CommandRegistry) -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Command reference\n\n");
    let _ = writeln!(
        out,
        "{} commands. Every user action is a command: the menus, the CLI (`forge cmd`), RPC \
         (`command.run`), MCP (one tool per command, name with `.` replaced by `_`) and \
         scripts (`run(id, #{{...}})`) all run the same handlers. Angles are degrees, \
         percentages as shown, node ids are integers.\n",
        registry.len()
    );
    out.push_str("| Id | Label | Undoable | MCP tool |\n|---|---|---|---|\n");
    for c in registry.iter() {
        let _ = writeln!(
            out,
            "| [`{id}`](#{anchor}) | {} | {} | `{}` |",
            cell(c.label()),
            if c.undoable() { "yes" } else { "no" },
            forge_mcp::tool_name(c.id()),
            id = c.id(),
            anchor = c.id().replace('.', "")
        );
    }
    let mut groups: BTreeMap<String, Vec<&dyn forge_command::CommandHandler>> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();
    for c in registry.iter() {
        let domain = c.id().split('.').next().unwrap_or("").to_string();
        if !groups.contains_key(&domain) {
            order.push(domain.clone());
        }
        groups.entry(domain).or_default().push(c);
    }
    for domain in order {
        let _ = writeln!(out, "\n## `{domain}`\n");
        for c in &groups[&domain] {
            let schema = c.args_schema();
            let _ = writeln!(out, "### `{}`\n", c.id());
            let _ = writeln!(
                out,
                "{}. {}\n",
                cell(c.label()),
                if c.undoable() {
                    "One undo step."
                } else {
                    "Not an undoable edit."
                }
            );
            if let Some(text) = schema.get("description").and_then(Value::as_str)
                && !text.starts_with("Arguments of a command that takes none")
            {
                let _ = writeln!(out, "{}\n", text.trim());
            }
            out.push_str(&schema_table(&schema));
            let _ = writeln!(
                out,
                "\nExample: `forge cmd scene.forge {} --args '{}'`\n",
                c.id(),
                c.sample_args()
            );
        }
    }
    out
}

// ---------------------------------------------------------------- CLI

fn usage_of(cmd: &Command, path: &str) -> String {
    let mut parts = vec![path.to_string()];
    for arg in cmd.get_arguments() {
        if arg.is_hide_set() || arg.get_id() == "help" || arg.get_id() == "json" {
            continue;
        }
        let name = if arg.is_positional() {
            format!("<{}>", arg.get_id().as_str())
        } else {
            let long = arg.get_long().unwrap_or("");
            if arg.get_num_args().is_some_and(|n| n.takes_values()) {
                format!("--{long} <{}>", arg.get_id().as_str().to_uppercase())
            } else {
                format!("--{long}")
            }
        };
        parts.push(if arg.is_required_set() {
            name
        } else {
            format!("[{name}]")
        });
    }
    parts.join(" ")
}

fn cli_markdown() -> String {
    let root = Cli::command();
    let mut out = String::from(HEADER);
    out.push_str("# `forge` command-line reference\n\n");
    let _ = writeln!(
        out,
        "{}.\n",
        root.get_about().map(|s| s.to_string()).unwrap_or_default()
    );
    out.push_str(
        "`forge-studio --headless <args>` runs the same tool. Add `--json` to any subcommand \
         for one JSON object on stdout (`{\"ok\": true, ...}` or `{\"ok\": false, \"error\": \
         {\"code\", \"message\"}}`); messages go to stderr.\n\n",
    );
    out.push_str("## Exit codes\n\n| Code | Meaning |\n|---|---|\n| 0 | ok |\n");
    let _ = writeln!(
        out,
        "| {EXIT_USER} | user error: bad arguments, unknown command id or node, a command that refuses, a failed script or RPC call |"
    );
    let _ = writeln!(
        out,
        "| {EXIT_LOAD} | the scene file cannot be read or loaded |"
    );
    let _ = writeln!(out, "| {EXIT_INTERNAL} | internal error (a bug) |");
    out.push_str("\n## Global options\n\n");
    out.push_str(&arg_table(&root, true));
    out.push_str("\n## Subcommands\n\n| Subcommand | Purpose |\n|---|---|\n");
    let subs: Vec<&Command> = root
        .get_subcommands()
        .filter(|s| s.get_name() != "help")
        .collect();
    for sub in &subs {
        let _ = writeln!(
            out,
            "| [`{0}`](#forge-{0}) | {1} |",
            sub.get_name(),
            cell(&sub.get_about().map(|s| s.to_string()).unwrap_or_default())
        );
    }
    for sub in subs {
        let _ = writeln!(out, "\n### `forge {}`\n", sub.get_name());
        let _ = writeln!(
            out,
            "{}\n",
            sub.get_about().map(|s| s.to_string()).unwrap_or_default()
        );
        let _ = writeln!(
            out,
            "```\n{}\n```\n",
            usage_of(sub, &format!("forge {}", sub.get_name()))
        );
        out.push_str(&arg_table(sub, false));
    }
    out
}

fn arg_table(cmd: &Command, globals: bool) -> String {
    let rows: Vec<_> = cmd
        .get_arguments()
        .filter(|a| a.get_id() != "help" && a.is_global_set() == globals && !a.is_hide_set())
        .collect();
    if rows.is_empty() {
        return "No options.\n".into();
    }
    let mut out =
        String::from("| Argument | Required | Default | Description |\n|---|---|---|---|\n");
    for arg in rows {
        let name = if arg.is_positional() {
            format!("`<{}>`", arg.get_id().as_str())
        } else {
            format!("`--{}`", arg.get_long().unwrap_or(""))
        };
        let default = arg
            .get_default_values()
            .iter()
            .map(|d| format!("`{}`", d.to_string_lossy()))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "| {name} | {} | {default} | {} |",
            if arg.is_required_set() { "yes" } else { "no" },
            cell(&arg.get_help().map(|s| s.to_string()).unwrap_or_default())
        );
    }
    out
}

// ---------------------------------------------------------------- RPC

fn rpc_markdown() -> String {
    use forge_rpc::docs::{ERRORS, METHODS, NOTIFICATIONS, limits};
    let mut out = String::from(HEADER);
    out.push_str("# RPC reference\n\n");
    out.push_str(
        "JSON-RPC 2.0, one object per line over TCP on `127.0.0.1`. Every request carries a \
         `\"token\"` member. Example:\n\n```\n{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"scene.get\",\"params\":{},\"token\":\"...\"}\n```\n\n\
         Command-shaped work goes through `command.run`; the command ids and arguments are in \
         the [command reference](commands.md).\n\n",
    );
    out.push_str("## Methods\n\n| Method | Params | Result | Description |\n|---|---|---|---|\n");
    for m in METHODS {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            m.name,
            code_cell(m.params),
            code_cell(m.result),
            cell(m.summary)
        );
    }
    out.push_str("\n## Notifications\n\nRequest-shaped lines without `id`, never answered.\n\n| Notification | Params | Sent when |\n|---|---|---|\n");
    for n in NOTIFICATIONS {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} |",
            n.name,
            code_cell(n.params),
            cell(n.sent_when)
        );
    }
    out.push_str("\n## Error codes\n\n| Code | Meaning |\n|---|---|\n");
    for e in ERRORS {
        let _ = writeln!(out, "| {} | {} |", e.code, cell(e.meaning));
    }
    out.push_str("\n## Limits\n\n| Limit | Value |\n|---|---|\n");
    for (name, value) in limits() {
        let _ = writeln!(out, "| {name} | {value} |");
    }
    out
}

fn code_cell(text: &str) -> String {
    if text == "-" {
        "-".into()
    } else {
        format!("`{}`", text.replace('|', "\\|"))
    }
}

// ---------------------------------------------------------------- MCP

fn mcp_markdown(app: App) -> String {
    let mut server = forge_mcp::Server::new(forge_mcp::HeadlessBackend::new(app));
    let reply = server
        .handle_line(r#"{"jsonrpc":"2.0","id":1,"method":"tools/list","params":{}}"#)
        .unwrap_or_default();
    let reply: Value = serde_json::from_str(&reply).unwrap_or(Value::Null);
    let tools = reply["result"]["tools"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let command_tools: Vec<String> = docs_app()
        .commands
        .iter()
        .map(|c| forge_mcp::tool_name(c.id()))
        .collect();

    let mut out = String::from(HEADER);
    out.push_str("# MCP reference\n\n");
    out.push_str(
        "`forge-mcp` speaks the Model Context Protocol over stdio. The tool list is the \
         command registry plus the tools below. Command tools take the arguments of the \
         [command](commands.md) with the same name (`.` becomes `_`). Tools that need a \
         viewport (`viewport_screenshot`) work only against a running editor.\n\n",
    );
    out.push_str("## Built-in tools\n\n");
    for t in tools
        .iter()
        .filter(|t| !command_tools.iter().any(|c| t["name"] == c.as_str()))
    {
        let _ = writeln!(out, "### `{}`\n", t["name"].as_str().unwrap_or(""));
        let _ = writeln!(out, "{}\n", cell(t["description"].as_str().unwrap_or("")));
        out.push_str(&schema_table(&t["inputSchema"]));
        out.push('\n');
    }
    out.push_str("## Command tools\n\n| Tool | Description |\n|---|---|\n");
    for t in tools
        .iter()
        .filter(|t| command_tools.iter().any(|c| t["name"] == c.as_str()))
    {
        let _ = writeln!(
            out,
            "| `{}` | {} |",
            t["name"].as_str().unwrap_or(""),
            cell(t["description"].as_str().unwrap_or(""))
        );
    }
    out
}

// ---------------------------------------------------------------- scripting

fn scripting_markdown() -> String {
    let opts = forge_script::ScriptOptions::default();
    let mut out = String::from(HEADER);
    out.push_str("# Rhai scripting reference\n\n");
    out.push_str(
        "`forge run script.rhai` (and the Script Manager panel) run [Rhai](https://rhai.rs/book/) \
         scripts. A script is a sequence of registry commands plus read-only scene queries; \
         there is no second API. One run is one undo step, and a failed run changes nothing. \
         Distances are scene units, angles degrees, node ids integers.\n\n",
    );
    for group in forge_script::api::groups() {
        let _ = writeln!(out, "## {group}\n\n| Call | Description |\n|---|---|");
        for entry in forge_script::api::API.iter().filter(|e| e.group == group) {
            let _ = writeln!(out, "| `{}` | {} |", entry.signature, cell(entry.summary));
        }
        out.push('\n');
    }
    out.push_str("## Commands not available in scripts\n\n");
    let blocked: Vec<String> = forge_script::BLOCKED_COMMANDS
        .iter()
        .map(|c| format!("`{c}`"))
        .collect();
    let _ = writeln!(out, "{}. `file.export_*` is allowed.\n", blocked.join(", "));
    out.push_str("## Sandbox limits\n\nNo modules or `import`, no `eval`, no clock, no file or network access.\n\n| Limit | Default |\n|---|---|\n");
    let _ = writeln!(out, "| operations | {} |", opts.max_operations);
    let _ = writeln!(out, "| wall-clock time | {} s |", opts.timeout.as_secs());
    let _ = writeln!(out, "| commands per run | {} |", opts.max_commands);
    let _ = writeln!(out, "| call depth | {} |", opts.max_call_levels);
    out
}
